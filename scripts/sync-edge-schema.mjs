// Copies the app's schema + parser into the edge function so client and server
// validate against exactly the same rules. Run: npm run sync:edge
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const header = '// GENERATED by scripts/sync-edge-schema.mjs from src/domain — do not edit.\n';

export function edgeVersion(file) {
  const source = readFileSync(join(root, 'src/domain', file), 'utf8');
  return header + source.replace(/from '\.\/schema'/g, "from './schema.ts'");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const file of ['schema.ts', 'parse.ts']) {
    writeFileSync(join(root, 'supabase/functions/analyze-decision', file), edgeVersion(file));
  }
  console.log('Synced schema.ts and parse.ts into supabase/functions/analyze-decision');
}
